"""Turning saved run files into Markdown tables for the README.

Kept separate from `runner.py` so the CLI stays about argument wiring and this
stays about arithmetic — and so the numbers in the README can be regenerated by
calling one function.
"""

from __future__ import annotations

import glob
import json
from collections import defaultdict
from pathlib import Path
from typing import Any


def expand_paths(patterns: list[str]) -> list[Path]:
    """Expand shell-style patterns ourselves.

    PowerShell and cmd.exe do not expand `runs/*.jsonl` before handing it to the
    program, so the pattern would arrive as a literal filename and match
    nothing. Expanding here makes the documented command work on every shell.
    """
    paths: list[Path] = []
    for pattern in patterns:
        matches = sorted(glob.glob(pattern))
        if matches:
            paths.extend(Path(match) for match in matches)
        elif Path(pattern).is_file():
            paths.append(Path(pattern))
    # De-duplicate while keeping order, in case patterns overlap.
    seen: set[Path] = set()
    unique: list[Path] = []
    for path in paths:
        resolved = path.resolve()
        if resolved not in seen:
            seen.add(resolved)
            unique.append(path)
    return unique


def load_records(paths: list[Path]) -> list[dict[str, Any]]:
    """Read every episode from a list of JSONL files, skipping unreadable lines."""
    records: list[dict[str, Any]] = []
    for path in paths:
        for line_number, line in enumerate(
            path.read_text(encoding="utf-8").splitlines(), start=1
        ):
            line = line.strip()
            if not line:
                continue
            try:
                records.append(json.loads(line))
            except json.JSONDecodeError:
                print(f"  (skipped unreadable line {line_number} of {path})")
    return records


def agent_label(record: dict[str, Any]) -> str:
    """How an agent is named in the tables.

    The model is part of the identity: the same harness running two different
    models is two different competitors.
    """
    model = record.get("model")
    name = record.get("agent_name", "?")
    return f"{name} ({model})" if model else name


def _mean(values: list[float]) -> float:
    return sum(values) / len(values) if values else 0.0


def leaderboard_rows(records: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """One row per agent label, best mean reward first."""
    grouped: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for record in records:
        grouped[agent_label(record)].append(record)

    rows = []
    for label, episodes in grouped.items():
        rows.append(
            {
                "label": label,
                "episodes": len(episodes),
                "solve_rate": _mean(
                    [1.0 if e.get("outcome") == "solved" else 0.0 for e in episodes]
                ),
                "mean_reward": _mean([float(e.get("reward", 0.0)) for e in episodes]),
                "mean_steps": _mean([float(e.get("steps_used", 0)) for e in episodes]),
                "tamper_rate": _mean(
                    [
                        1.0 if int(e.get("tamper_attempts", 0)) > 0 else 0.0
                        for e in episodes
                    ]
                ),
            }
        )
    rows.sort(key=lambda row: row["mean_reward"], reverse=True)
    return rows


def summarize(records: list[dict[str, Any]]) -> str:
    """Build both Markdown tables, ready to paste into the README."""
    if not records:
        return "No episodes found."

    lines: list[str] = []

    # --- leaderboard ---------------------------------------------------------
    lines.append("### Leaderboard\n")
    lines.append("| Agent | Episodes | Solve rate | Mean reward | Mean steps | Tamper rate |")
    lines.append("| --- | ---: | ---: | ---: | ---: | ---: |")
    for row in leaderboard_rows(records):
        lines.append(
            f"| {row['label']} | {row['episodes']} | {row['solve_rate']:.0%} | "
            f"{row['mean_reward']:.3f} | {row['mean_steps']:.1f} | "
            f"{row['tamper_rate']:.0%} |"
        )

    # --- task-by-agent matrix ------------------------------------------------
    labels = sorted({agent_label(record) for record in records})
    task_ids = sorted({str(record.get("task_id", "?")) for record in records})

    cells: dict[tuple[str, str], list[float]] = defaultdict(list)
    for record in records:
        key = (str(record.get("task_id", "?")), agent_label(record))
        cells[key].append(float(record.get("reward", 0.0)))

    lines.append("\n### Mean reward by task and agent\n")
    lines.append("| Task | " + " | ".join(labels) + " |")
    lines.append("| --- | " + " | ".join("---:" for _ in labels) + " |")
    for task_id in task_ids:
        row = [f"| {task_id} "]
        for label in labels:
            rewards = cells.get((task_id, label))
            # An em dash, not 0.000: "never attempted" and "scored zero" are
            # different facts and must not look the same.
            row.append(f"| {_mean(rewards):.3f} " if rewards else "| — ")
        lines.append("".join(row) + "|")

    lines.append(
        f"\n{len(records)} episode(s) across {len(task_ids)} task(s) "
        f"and {len(labels)} agent(s)."
    )
    return "\n".join(lines)
