import { notFound } from "next/navigation";

import { DifficultyBadge } from "@/components/badges";
import { EpisodeTable } from "@/components/episode-table";
import { ApiDown, Card, PageHeading, StatTile } from "@/components/layout-bits";
import { getEpisodes, getTask, percent, reward } from "@/lib/api";

/**
 * A live results dashboard: every page reads fresh data on each request, so the
 * route blocks on the API instead of being prerendered into a static shell.
 * Without this, Next's Cache Components check fails the build.
 *
 * Known trade-off: this route is partially prerendered, so the 200 response
 * headers are already flushed (`x-nextjs-postponed: 1`) by the time the data
 * arrives and `notFound()` runs below. A missing id therefore renders the
 * not-found page with a 200 rather than a 404 — a "soft 404". Opting out of
 * PPR would fix the status, at the cost of showing nothing at all until the API
 * answers, which on a free tier waking from sleep is 30-60 seconds. For a
 * results dashboard with no SEO requirement, the instant shell is worth more
 * than the correct status code. Next's own /no-such-page 404 is unaffected.
 */
export const instant = false

// `params` is a promise in the App Router and must be awaited. PageProps is
// generated by `next typegen`, so the route path itself is type-checked: a typo
// in "/tasks/[id]" fails the build instead of 404-ing at runtime.
type Props = PageProps<"/tasks/[id]">;

export async function generateMetadata({ params }: Props) {
  const { id } = await params;
  const task = await getTask(id);
  return { title: task ? task.title : id };
}

export default async function TaskPage({ params }: Props) {
  const { id } = await params;
  const task = await getTask(id);

  // `null` covers both "API is down" and "no such task". Check the API first:
  // if the list endpoint answers, the task genuinely does not exist.
  if (!task) {
    const reachable = await getEpisodes({ limit: 1 });
    if (reachable === null) {
      return (
        <>
          <PageHeading title={id} />
          <ApiDown what="this task" />
        </>
      );
    }
    notFound();
  }

  const episodes = await getEpisodes({ taskId: id, limit: 200 });

  return (
    <>
      <PageHeading title={task.title}>
        <div className="mt-3 flex flex-wrap items-center gap-2 text-sm">
          <code className="rounded-md border border-edge bg-surface px-2 py-0.5 font-mono text-xs">
            {task.id}
          </code>
          <DifficultyBadge difficulty={task.difficulty} />
          <span className="text-muted">{task.category}</span>
        </div>
      </PageHeading>

      <div className="mb-8 grid grid-cols-2 gap-3 sm:grid-cols-4">
        <StatTile label="Episodes" value={task.episodes} />
        <StatTile
          label="Solve rate"
          value={task.episodes ? percent(task.solve_rate) : "—"}
        />
        <StatTile
          label="Mean reward"
          value={task.episodes ? reward(task.mean_reward) : "—"}
        />
        <StatTile
          label="Step limit"
          value={task.max_steps}
          hint="then it auto-submits"
        />
      </div>

      <div className="space-y-8">
        <Card
          title="What the agent is told"
          hint="This is the whole brief. It never mentions where the bug is, and never mentions the hidden tests."
        >
          <p className="whitespace-pre-wrap px-4 py-4 text-sm leading-relaxed">
            {task.description}
          </p>
        </Card>

        <Card title={`Episodes (${episodes?.length ?? 0})`}>
          {episodes === null ? (
            <div className="p-4">
              <ApiDown what="the episodes for this task" />
            </div>
          ) : (
            <EpisodeTable episodes={episodes} />
          )}
        </Card>
      </div>
    </>
  );
}
